/**
 * Regenerates the parts of the README that state facts, from the artifacts.
 *
 * The README used to carry a hand-typed run table that contradicted the
 * receipts. A judge who cross-checks sees the contradiction first, so the
 * numbers in the prose are now generated and the source is named.
 *
 *   npm run readme
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { REPO_ROOT, type Receipts } from "../src/proof.js";

const BEGIN = "<!-- BEGIN:GENERATED -->";
const END = "<!-- END:GENERATED -->";

function money(value: string | number | null | undefined): string {
  if (value === null || value === undefined) return "—";
  return `$${value}`;
}

async function main() {
  const readmePath = path.join(REPO_ROOT, "README.md");
  const readme = await readFile(readmePath, "utf8");
  let receipts: Receipts;
  try {
    receipts = JSON.parse(
      await readFile(path.join(REPO_ROOT, "docs", "receipts.json"), "utf8"),
    ) as Receipts;
  } catch {
    console.log("no docs/receipts.json — the README was not touched");
    return;
  }

  const paid = receipts.steps.filter((step) => step.outcome === "paid");
  const refused = receipts.steps.filter((step) => step.outcome === "refused");
  const counterfactual = receipts.counterfactual;

  const rows = receipts.steps
    .map((step) => {
      const outcome =
        step.outcome === "paid"
          ? `**paid** — \`${step.tx_hash ?? "no hash"}\``
          : `**refused** — \`${step.error_code ?? "?"}\``;
      return `| ${step.n} | \`${step.endpoint}\` | ${money(step.price_usd)} | ${outcome} |`;
    })
    .join("\n");

  const facts = counterfactual.facts
    .map((fact) => {
      const state = fact.covered
        ? "**covered**"
        : fact.blocked_attempt
          ? `**blocked** — ${fact.blocked_attempt.blocked_by} (${money(fact.blocked_attempt.wanted_price_usd)})`
          : "**not attempted** — the budget was gone";
      return `| ${fact.fact} | ${state} |`;
    })
    .join("\n");

  const generated = `<!-- GENERATED BY \`npm run readme\` FROM docs/receipts.json. Do not edit by hand. -->
### The recorded run

Session \`${receipts.session.session_id ?? "—"}\`: up to **${money(receipts.session.max_amount_per_tx)}** per
call, **${money(receipts.session.max_total_amount)}** in total. The agent was asked for a
cautious assessment of ETH.

| # | What it tried | Price | Outcome |
| --- | --- | --- | --- |
${rows}

**${money(receipts.totals.spent_usd)} spent of ${money(receipts.totals.session_budget_usd)}.**
${receipts.totals.payments} settled on chain, ${receipts.totals.refusals} refused by the Passport.

### What the limit cost

The refusals were not free attempts — they were evidence the agent wanted and did not get:

| The answer needed | What the record says |
| --- | --- |
${facts}

**The limit cost ${money(counterfactual.cost_usd)} of evidence against a
${money(counterfactual.budget_usd)} budget — ${counterfactual.budget_multiplier ?? "?"}× the whole
budget.** ${counterfactual.unattempted_facts.length ? `The agent never got to try ${counterfactual.unattempted_facts.join(", ")}.` : ""}
`;

  if (!readme.includes(BEGIN) || !readme.includes(END)) {
    console.log("the README has no generated block; nothing to do");
    return;
  }
  const start = readme.indexOf(BEGIN);
  const end = readme.indexOf(END) + END.length;
  await writeFile(readmePath, `${readme.slice(0, start)}${BEGIN}\n${generated}${END}${readme.slice(end)}`);
  console.log("README.md: the run table and the cost of the limit regenerated");
}

await main();
